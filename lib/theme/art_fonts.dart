/// محرك الاقتران الطباعي — الفرق بين «نصّ مكتوب» و«نصّ مصمَّم».
///
/// اللوحة اللونية عندنا تُبنى بعلاقة (`ArtPalette`): أساسٌ ومرافقٌ يقابله
/// وحياديّ يريح العين. والطباعة كانت بلا علاقة أصلًا: **خطّ واحد لكل
/// التصميم**، عنوانه ومتنه وزرّه — يتفاوت وزنًا وحجمًا لا شخصيّة.
///
/// وهذا أكثر ما يفرّق تصميم كانفا عن تصميمنا في النظرة الأولى. المصمّم
/// البشري لا يكبّر الخط ليصنع عنوانًا، بل **يغيّر الوجه**: وجهٌ ذو شخصية
/// للعنوان، ووجهٌ صامت للمتن. والعين تقرأ الفرق قبل أن تقرأ الكلمات.
///
/// وثلاثة قرارات هنا تستحق التسمية:
///
///   ١) **الوجه دورٌ لا اسم.** المواصفة تقول `SpecFont.display` لا
///      `'Reem Kufi'` — كما تقول `ColorRole.complement` لا `#E1A83B`.
///      فالنموذج لا يعرف ما في حزمتنا من خطوط ولا يجب أن يعرف، ولو
///      أخرج اسمًا صريحًا لاخترع وجهًا غير موجود فسقط النصّ إلى
///      الافتراضي بصمت.
///
///   ٢) **الاقتران يُختار من قائمة مغلقة.** حرّيةُ جمع أيّ وجهين تُخرج
///      اقترانات قبيحة أكثر مما تُخرج جميلة — وجهان متشابهان يبدوان
///      غلطةً مطبعية، ووجهان صاخبان يتنازعان. فالأزواج الأربعة أدناه
///      مقيسة العلاقة: في كلٍّ منها وجهٌ له شخصية ووجهٌ يصمت.
///
///   ٣) **خطّ العلامة يغلب وجه العرض لا وجه المتن.** التاجر الذي اختار
///      خطًّا في هويّته اختاره ليُعرَف به، وموضعُ ذلك العنوانُ. وفرضُه
///      على المتن أيضًا يُلغي الاقتران ويعيدنا إلى خطٍّ واحد — أي أن
///      احترام اختياره حرفيًّا يُبطل الميزة كلّها.
library;

/// دور الوجه في التصميم — لا اسم العائلة.
enum SpecFont {
  /// وجه العنوان والشارة: ذو شخصية، يُقرأ من بعيد ويُعرَف.
  display,

  /// وجه المتن والوصف والهاشتاقات: صامت، يُقرأ ولا يُنظر إليه.
  text,

  /// وجه الدعوة إلى الإجراء: يتبع العرض ليبقى الزرّ ظاهرًا، ولا يأخذ
  /// وجهًا ثالثًا — ثلاثة وجوه في لوحة واحدة فوضى لا تنويع.
  accent,
}

/// زوجٌ مقيس: وجهٌ للعرض ووجهٌ للمتن.
class ArtFonts {
  const ArtFonts({
    required this.display,
    required this.text,
    required this.name,
    required this.note,
  });

  /// عائلة وجه العرض كما هي مسجَّلة في `pubspec.yaml`.
  final String display;

  /// عائلة وجه المتن.
  final String text;

  /// اسم الزوج — للتشخيص ولعرضه على التاجر.
  final String name;

  /// متى يصلح هذا الزوج. يُعرض في الشرح ويُفيد النموذج في الاختيار.
  final String note;

  /// الأزواج المتاحة. القائمة مغلقة عمدًا — راجع القرار (٢) أعلاه.
  ///
  /// وترتيبها ليس عبثًا: الأوّل هو ما يقع عليه `pairing = 0`، أي ما
  /// يراه من لم يختر شيئًا. فصُدّر أوسعُها صلاحيةً لا أغربُها.
  static const pairs = <ArtFonts>[
    ArtFonts(
      display: 'Reem Kufi',
      text: 'Tajawal',
      name: 'كوفي وحديث',
      note: 'كوفيّ هندسيّ يقرأ كشعار، ومتنٌ صامت. يصلح لأكثر النشاطات.',
    ),
    ArtFonts(
      display: 'Amiri',
      text: 'Almarai',
      name: 'نسخيّ وهادئ',
      note: 'نسخيٌّ بتباين سميك ورفيع — للفخم والموسميّ والتراثيّ.',
    ),
    ArtFonts(
      display: 'Lalezar',
      text: 'Cairo',
      name: 'ملصق عالي الصوت',
      note: 'ثقيلٌ ملصقيّ — للخصومات والعروض التي تُقرأ من الشارع.',
    ),
    ArtFonts(
      display: 'Cairo',
      text: 'Tajawal',
      name: 'سانس نظيف',
      note: 'اقترانٌ هادئ بلا شخصية صاخبة — للتقنيّ والطبّيّ والرسميّ.',
    ),
  ];

  /// يختار زوجًا بالرقم — كما تختار `ArtPalette.from` انسجامًا بـ`variant`.
  ///
  /// و[brandDisplay] خطّ العلامة إن اختاره التاجر: يحلّ محلّ وجه العرض
  /// وحده. وإن صادف أن ساوى وجهَ المتن سقط المتن إلى وجهٍ آخر من
  /// القائمة، إذ الاقتران بوجهين متطابقين ليس اقترانًا.
  factory ArtFonts.from(int pairing, {String? brandDisplay}) {
    final base = pairs[pairing.abs() % pairs.length];
    if (brandDisplay == null || brandDisplay.isEmpty) return base;

    final text = brandDisplay == base.text
        ? pairs.firstWhere(
            (p) => p.text != brandDisplay,
            orElse: () => base,
          ).text
        : base.text;

    return ArtFonts(
      display: brandDisplay,
      text: text,
      name: '${base.name} (بخط العلامة)',
      note: base.note,
    );
  }

  /// عائلة الوجه لدورٍ بعينه.
  String familyFor(SpecFont font) => switch (font) {
    SpecFont.display => display,
    SpecFont.accent => display,
    SpecFont.text => text,
  };

  @override
  String toString() => '$name ($display / $text)';
}
